def figure_macros():
    """{macro: [figure scripts]} from the FIGURE_MACROS tuple each figure script declares.
    Read as text, so the scripts are not run. A figure script without the tuple is a hard
    failure: the purge rule cannot know what it prints."""
    out = {}
    for p in sorted(FIGDIR.glob("fig_*.py")):
        s = p.read_text(encoding="utf-8")
        m = re.search(r"^FIGURE_MACROS\s*=\s*\((.*?)\)", s, re.MULTILINE | re.DOTALL)
        if not m:
            raise SystemExit(f"[ERROR] {p.name} declares no FIGURE_MACROS tuple")
        for name in re.findall(r'"([A-Za-z]+)"', m.group(1)):
            out.setdefault(name, []).append(p.name)
    return out


def macros_in_use():
    """The purge rule: a macro is used if paper.tex, a tables/*.tex file or a
    figure script's FIGURE_MACROS names it. LaTeX comments do not count."""
    if not MANU.is_dir():
        raise SystemExit("[ERROR] --list-unused reads manuscript/paper.tex, and manuscript/ is not "
                         "present.")
    used = set(figure_macros())
    for f in [MANU / "paper.tex"] + sorted((MANU / "tables").glob("*.tex")):
        txt = "\n".join(re.sub(r"(?<!\\)%.*$", "", l)
                        for l in f.read_text(encoding="utf-8").split("\n"))
        used |= set(re.findall(r"\\([A-Za-z]+)", txt))
    return used


def previous_values():
    """{name: value} of the manuscript values.tex as it stands BEFORE this run, or {} if it
    does not exist. This is read for VALUES_DIFF.md only, a report. Neither the
    list of macros nor any value or precision written to values_generated.tex comes from it,
    so the file can be deleted before a run and the run writes the same bytes.
    Without manuscript/ (the public package), the previous file is the committed
    02_output/values/values_generated.tex, which the manuscript's copy equals byte for byte;
    it is read here, before this run overwrites it."""
    if not MANU.is_dir():
        if not (VALDIR / "values_generated.tex").exists():
            return {}
        return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{((?:[^{}]|\{[^{}]*\})*)\}",
                               (VALDIR / "values_generated.tex").read_text(encoding="utf-8")))
    if not MANU_VALUES.exists():
        return {}
    # A value may carry ONE level of braces (a unit such as {}^{\circ}\mathrm{C}^{-1}).
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{((?:[^{}]|\{[^{}]*\})*)\}",
                           MANU_VALUES.read_text(encoding="utf-8")))


def compare(prev_val, gen_val):
    """Verdict for VALUES_DIFF.md. Compares and reports; it changes nothing. (Until step
    29 bis this was match_precision, which REFORMATTED the generated value to the previous
    file's precision: the previous run's output was then an input of this one.)"""
    if prev_val is None:
        return "NEW (not in the previous values.tex)"
    pv = prev_val.replace("\\%", "").replace("%", "")
    gv = gen_val.replace("\\%", "").replace("%", "")
    if pv == gv:
        return "MATCH"
    try:
        d = float(gv) - float(pv)
    except ValueError:
        return "diff:check"
    rel = abs(d) / abs(float(pv)) if float(pv) else 1
    if d == 0:
        return "diff:format (same number, other digits)"
    if abs(d) <= 0.5 or rel <= 0.01:
        return f"diff:benign (Δ={d:+g})"
    return f"diff:SUBSTANTIVE (Δ={d:+g})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--collect", action="store_true", help="re-run collect_computed.py first")
    ap.add_argument("--list-unused", action="store_true",
                    help="list the macros this run emits that the purge rule finds unused "
                         "(paper.tex, tables/*.tex, FIGURE_MACROS), and exit")
    args = ap.parse_args()

    # The purge rule, enforced: no figure may lose a number it prints or draws.
    fig = figure_macros()
    clash = sorted(set(fig) & REMOVED_MACROS)
    if clash:
        print("ERROR: REMOVED_MACROS drops macros that a figure prints or draws:")
        for name in clash:
            print(f"         \\{name}  ({', '.join(fig[name])})")
        return 1
    if args.collect or not COMPUTED.exists():
        subprocess.run([sys.executable, str(HERE / "collect_computed.py")], check=True)

    computed = json.loads(COMPUTED.read_text(encoding="utf-8"))
    # THE LIST OF MACROS COMES FROM THE GENERATORS ONLY: the keys of
    # computed.json and the sourced constants of inputs_literature.py, minus REMOVED_MACROS.
    # Until then it was read from manuscript/values.tex, so a run from an empty directory
    # failed on the missing file, and a value's precision was copied from the previous file.
    emitted_comp = sorted(set(computed) - REMOVED_MACROS)
    emitted_lit = sorted(set(LITERATURE_MACROS) - REMOVED_MACROS)
    clash = sorted(set(emitted_comp) & set(emitted_lit))
    if clash:
        print("ERROR: macro(s) both computed and sourced: " + ", ".join(clash))
        return 1
    # Every number a figure prints or draws must be emitted by this run.
    missing_fig = sorted(set(fig) - set(emitted_comp) - set(emitted_lit))
    if missing_fig:
        print("ERROR: FIGURE_MACROS name macro(s) that no generator emits:")
        for name in missing_fig:
            print(f"         \\{name}  ({', '.join(fig[name])})")
        return 1
    if args.list_unused:
        used = macros_in_use()
        unused = [n for n in emitted_lit + emitted_comp if n not in used]
        print(f"{len(unused)} macro(s) emitted but unused by paper.tex, tables/*.tex and "
              f"FIGURE_MACROS:")
        for n in unused:
            print(f"  \\{n}")
        return 0

    prev = previous_values()   # VALUES_DIFF.md only
    VALDIR.mkdir(parents=True, exist_ok=True)
    TABDIR.mkdir(parents=True, exist_ok=True)

    lit_lines, comp_lines, diff_rows = [], [], []
    BS = chr(92)
    for name in emitted_lit:
        val, src = LITERATURE_MACROS[name]
        lit_lines.append(BS + "newcommand{" + BS + name + "}{" + val + "}   % " + src)
        diff_rows.append((name, prev.get(name, "—"), val, "INPUT", compare(prev.get(name), val), src))
    for name in emitted_comp:
        c = computed[name]
        # The value is written as the generator formatted it. Each generator chooses its own
        # rounding (collect_computed.py or the script whose MACROS block it parses).
        gen = c["value"]
        comp_lines.append(BS + "newcommand{" + BS + name + "}{" + gen + "}   % " + c["source"]
                          + ("  [requires network]" if c["requires_network"] else ""))
        diff_rows.append((name, prev.get(name, "—"), gen, "COMPUTED", compare(prev.get(name), gen),
                          c["source"]))
    gone = sorted(set(prev) - set(emitted_comp) - set(emitted_lit))
    for name in gone:
        diff_rows.append((name, prev[name], "—", "—", "DROPPED (in the previous values.tex, "
                          "not emitted by this run)", ""))

    # ── assemble values_generated.tex ──
    # No generation timestamp is written here on purpose. A date would differ between two
    # runs of the same inputs, and byte-identical output across runs is the property that
    # makes the value chain checkable at all. The generation date of this file is
    # the date of the commit that carries it, which git already keeps and cannot be edited
    # by hand. Every macro instead carries the script and the inputs it came from.
    header = ["% GENERATED FILE — DO NOT EDIT. Written by 01_code/04_tables_values/make_tables_values.py",
              "% and copied to manuscript/values.tex by step 3/5 of run_all.sh. Every edit",
              "% made here is overwritten at the next run; change the generator instead. The trailing",
              "% comment on each macro is REPORTED, not authored: it is the 'source' string",
              "% that collect_computed.py attached to the value, and it describes where the",
              "% number came from, not what the macro means. This is not a source file.",
              "%",
              "% values_generated.tex — CANDIDATE values.tex written by make_tables_values.py.",
              "% DO NOT EDIT BY HAND: regenerate with run_all.sh (or make_tables_values.py).",
              "% Drop-in for \\input{values.tex}: every macro is defined.",
              "% Block 1 = sourced literature inputs; Block 2 = code-regenerated outputs.",
              "% There is no third block. Every macro here is either sourced or computed;",
              "% a macro that is neither fails the run by name rather than being copied",
              "% through from the previous run's output.",
              "% Generation date = the commit that carries this file; no timestamp is written",
              "% inline, so that two runs of the same inputs stay byte-identical.", ""]
    body = (["% ===== (1) Literature inputs (sourced constants, NOT computed) ====="] + sorted(lit_lines)
            + ["", "% ===== (2) Computed outputs (regenerated by the code) ====="] + sorted(comp_lines) + [""])
    (VALDIR / "values_generated.tex").write_text("\n".join(header + body), encoding="utf-8", newline="\n")

    # ── counts.json: the ONE place the macro counts are established ──
    # These numbers are quoted in three prose passages -- the data-availability section of
    # README.md, the network-failure message of run_all.sh, and section 4 of README.md --
    # and each used to carry its own copy. They disagreed, and the example is worth keeping
    # because the two numbers were both real: in 2026-09 the README said "36 of the 75
    # computed macros in values.tex require network", which were computed.json's totals and
    # not this file's -- values.tex carried 72 computed macros then, 35 of them network, the
    # 36th being a macro in REMOVED_MACROS that never reaches it. (Those figures are that
    # date's, not today's; today's are below, computed.) A count that describes this file has
    # to be taken FROM this file, at the moment it is written, which is here.
    # Every consumer reads counts.json; none of them counts anything itself.
    counts = {
        "literature": len(lit_lines),
        "computed": len(comp_lines),
        "computed_network": sum(1 for l in comp_lines if "[requires network]" in l),
        "total": len(lit_lines) + len(comp_lines),
        "computed_json_entries": len(computed),
        "note": "counts of manuscript/values.tex as written by make_tables_values.py. "
                "'computed_json_entries' is the larger number in computed.json, which "
                "includes macros listed in REMOVED_MACROS that are never emitted.",
    }
    (VALDIR / "counts.json").write_text(json.dumps(counts, indent=2) + "\n", encoding="utf-8", newline="\n")

    write_disagreements()
    write_eps_dyn(computed)

    # ── VALUES_DIFF.md ──
    n_lit = sum(1 for r in diff_rows if r[3] == "INPUT")
    n_comp = sum(1 for r in diff_rows if r[3] == "COMPUTED")
    n_match = sum(1 for r in diff_rows if r[3] == "COMPUTED" and r[4] == "MATCH")
    n_benign = sum(1 for r in diff_rows if r[3] == "COMPUTED" and r[4].startswith("diff:benign"))
    n_sub = sum(1 for r in diff_rows if r[3] == "COMPUTED" and "SUBSTANTIVE" in r[4])
    out = [
        "# VALUES_DIFF.md — generated values vs manuscript snapshot (Stage A, non-destructive)",
        "",
        f"Macros: **{n_lit} literature-input**, **{n_comp} computed**. There is no "
        "carried-over family: a macro with no generator and no sourced value fails the run.",
        f"Computed verdicts: {n_match} match, {n_benign} benign (MC noise/rounding), **{n_sub} substantive**.",
        "",
        "The manuscript is NOT modified. `diff:benign` = within MC noise / rounding; "
        "`diff:SUBSTANTIVE` = inspect before adopting (Stage B). `INPUT` rows should match by "
        "construction (literature value = paper value).",
        "",
        "| Macro | Paper | Generated | Family | Verdict | Source |",
        "|---|---|---|---|---|---|",
    ]
    for name, pv, gv, fam, verdict, src in diff_rows:
        out.append(f"| `\\{name}` | {pv} | {gv} | {fam} | {verdict} | {src} |")
    (VALDIR / "VALUES_DIFF.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    print(f"values_generated.tex: {n_lit} input + {n_comp} computed.")
    print(f"VALUES_DIFF.md: {n_match} match, {n_benign} benign, {n_sub} SUBSTANTIVE.")
    print("Manuscript untouched (Stage A).")
    return 0


