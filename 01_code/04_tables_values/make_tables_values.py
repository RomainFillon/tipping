"""
REPLICATION HEADER
  PRODUCES   02_output/values/values_generated.tex, VALUES_DIFF.md,
             02_output/tables/disagreements.tex and 02_output/tables/eps_dyn.tex
  FEEDS      manuscript/values.tex, tab:disagreements, tab:eps_dyn
  INPUTS     computed.json, inputs_literature.py (the previous manuscript/values.tex, if any,
             is read for VALUES_DIFF.md only)
  SEED       none
  RUNTIME    about 4 s
  IMPLEMENTS no equation; the value-generation stage

make_tables_values.py — STAGE A generator (safe, diffable, NON-destructive).

Reads the sourced literature inputs (inputs_literature.py) and the regenerated computed
outputs (02_output/computed.json, produced by collect_computed.py) and writes:

  02_output/values/values_generated.tex   candidate values.tex (every macro defined),
                                           in TWO labelled blocks:
                                             (1) Literature inputs  (sourced constants)
                                             (2) Computed outputs   (regenerated by code)
  02_output/tables/disagreements.tex       tab:disagreements (cells are macros of values.tex)
  02_output/tables/eps_dyn.tex             tab:eps_dyn (cells are macros of values.tex)
  02_output/values/VALUES_DIFF.md          per-macro diff: paper vs generated, classified

Anti-fabrication: a computed value comes only from computed.json (a real run). A literature
value comes only from inputs_literature.py (sourced). A macro that is NEITHER stops the run
and is named on the way out. There is no third path. The list of macros
itself comes from the generators (computed.json keys and inputs_literature.py, minus
REMOVED_MACROS), and every value is written as its generator formatted it: the previous
values.tex can be deleted before a run without changing a byte of the output.

Why there is no third path, and specifically no fallback that copies the manuscript's own
value: manuscript/values.tex is not an independent record of anything. Step 3/5 of
run_all.sh overwrites it with the file this script writes, so a value taken from it would
be read out of the previous run's output and written straight back into the next one, and
would agree with itself for as long as nobody looked. A fallback that quietly preserves a
number is not the conservative option; it is the one failure a reproduction check cannot
detect. Hence: named, and fatal.

NOTHING here overwrites the manuscript (Stage A).

Usage:  python make_tables_values.py        (uses existing computed.json)
        python make_tables_values.py --collect   (re-run collect_computed.py first)
"""
