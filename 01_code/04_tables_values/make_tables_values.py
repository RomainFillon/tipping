def write_eps_dyn(computed):
    """Write eps_dyn.tex (tab:eps_dyn, the appendix on where the elements sit): the lower edge of the fixed-budget
    regime and the factor F by which the leading law lifts the price between today's
    proximity and eps_dyn (the width of the window; the lift of the full price only if the
    state is inside the noise layer today), per element and recovery rate, on the
    three emission paths. The caption and the note are in paper.tex, around the \\input. Every number is a macro of values.tex (collect_computed.py). An F
    cell reads "---" where eps_dyn >= eps_now: the lower edge already lies above today's
    proximity and the geometry lifts nothing; that is decided here from computed.json, the
    same file the macros come from, so the dash and the macro cannot disagree."""
    rows = [  # (element, recovery rate cell, eps_now macro, case suffix)
        ("AMOC", "$\\thetaAMOChat$, record", "epsAMOCnat", "AMOC"),
        ("Amazon", "$\\kappaAmazonBoulton$, vegetation index", "epsAmazonnat", "AmazonBoulton"),
        ("Amazon", "one per century, assumed", "epsAmazonnat", "AmazonSlow"),
        ("West Antarctic ice sheet", "$1/\\relaxWAISHillLo$, flow", "epsWAISnat", "WAISfast"),
        ("West Antarctic ice sheet", "$1/\\relaxWAISHillHi$, flow", "epsWAISnat", "WAISslow"),
        ("West Antarctic ice sheet", "one per century, slower modes", "epsWAISnat", "WAIScentury"),
    ]
    lines = [
        "% GENERATED FILE — produced by make_tables_values.py (write_eps_dyn). Every number is a",
        "% macro of values.tex; an F cell is --- where eps_dyn >= eps_now (computed.json).",
        "\\begin{tabular}{@{}llccccccc@{}}",
        "\\toprule",
        " & & & \\multicolumn{2}{c}{Today's rate} & \\multicolumn{2}{c}{SSP2-4.5} "
        "& \\multicolumn{2}{c}{SSP3-7.0} \\\\",
        "\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(l){8-9}",
        "Element & Recovery rate $\\theta$ (per year) & $\\eps_{\\mathrm{now}}$ "
        + "& $\\eps_{\\mathrm{dyn}}$ & $F$ " * 3 + "\\\\",
        "\\midrule",
    ]
    for el, theta, now, suf in rows:
        cells = [el, theta, "$\\" + now + "$"]
        for pkey in ("", "SSPmid", "SSPhigh"):
            e_name, a_name = f"epsDyn{suf}{pkey}", f"amp{suf}{pkey}"
            if e_name not in computed or a_name not in computed:
                raise SystemExit(f"[ERROR] write_eps_dyn: {e_name} or {a_name} missing "
                                 "from computed.json")
            enters = float(computed[e_name]["value"]) < float(computed[now]["value"])
            cells += ["$\\" + e_name + "$", ("$\\" + a_name + "$") if enters else "---"]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (TABDIR / "eps_dyn.tex").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("  regenerated 02_output/tables/eps_dyn.tex")


